-- helpers -----------------------------------------------------------------
local function struct(p) return (p == 1) and 0x1000 or 0x1080 end
local function posx(b) return ram(b + 0x21) + 256 * ram(b + 0x22) end
local function setx(b, x) wr(b + 0x21, x % 256); wr(b + 0x22, math.floor(x / 256)) end
local function park(att, range)          -- defender parked `range` px from attacker
  local ab, db = struct(att), struct(3 - att)
  local ax = posx(ab)
  local L = ax <= posx(db)
  setx(db, L and (ax + range) or (ax - range))
  wr(db + 0x49, 0x60); wr(0x800 + (2 - att), 0x60)
end
local function onLeft(att)
  return posx(struct(att)) <= posx(struct(3 - att))
end
local function dirpad(c, L)
  local m = { down = (c == "1" or c == "2" or c == "3"), up = (c == "7" or c == "8" or c == "9") }
  local fwd = (c == "3" or c == "6" or c == "9")
  local back = (c == "1" or c == "4" or c == "7")
  if fwd then if L then m.right = true else m.left = true end end
  if back then if L then m.left = true else m.right = true end end
  return m
end
-- motion driver: from pt0, `stepf` frames per step (default 3), button on step n+1
local function motion(api, player, mstr, btn, pt0, neutralBtn, stepf)
  local pt = api.pt
  local L = onLeft(player)
  local sd = math.floor((pt - pt0) / (stepf or 3)) + 1
  if pt >= pt0 and sd <= #mstr then
    pulse[player - 1] = dirpad(mstr:sub(sd, sd), L)
  elseif pt >= pt0 and sd == #mstr + 1 then
    local p = neutralBtn and {} or dirpad(mstr:sub(#mstr, #mstr), L)
    p[btn] = true
    pulse[player - 1] = p
  elseif pt >= pt0 and sd == #mstr + 2 then
    pulse[player - 1] = nil
  end
end
-- Per-address damage streams (issue #16): each player's HP walk is tracked against
-- its own previous value, seeded from live RAM at test start (testT0) rather than a
-- hardcoded 0x60. total() sums both players by default; total(1)/total(2) isolate one.
local function total(player)
  local tot, byk = 0, {}
  local prev = { [0x1049] = hpSeed[0x1049] or 0x60, [0x10C9] = hpSeed[0x10C9] or 0x60 }
  local want = player and ((player == 1) and 0x1049 or 0x10C9) or nil
  for _, h in ipairs(hits) do
    local d = (prev[h.addr] or 0x60) - h.v; prev[h.addr] = h.v
    if d > 0 and (not want or h.addr == want) then
      tot = tot + d; byk[h.kind] = (byk[h.kind] or 0) + d
    end
  end
  return tot, byk
end
local function ck(cond, msg) return cond, msg end
local function grabsum(byk) return (byk.TOSS or 0) + (byk.TICK or 0) + (byk.GRAB or 0) end
local function grabwrites()
  local n = 0
  for _, h in ipairs(hits) do if h.kind == "TICK" or h.kind == "TOSS" or h.kind == "GRAB" then n = n + 1 end end
  return n
end

