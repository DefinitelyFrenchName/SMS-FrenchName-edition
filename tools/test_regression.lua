local idx, phase, settle = 0, "boot", 0
emu.addEventCallback(function()
  t = t + 1
  if t == 0 then
    -- static layer
    -- Name the ROM in the header: this file is read by tools and by people, and
    -- "which build produced this verdict" was previously answerable only from
    -- memory. emu.getRomInfo() is not available in every headless build, so this
    -- degrades to the plain header rather than failing the run.
    local okri, ri = pcall(emu.getRomInfo)
    log("=== regression run ===" .. ((okri and ri and ri.name) and ("  rom=" .. tostring(ri.name)) or ""))
    for pn, sig in pairs(SIGS) do
      local ok = true
      for _, s in ipairs(sig) do if rom(s[1]) ~= s[2] then ok = false break end end
      has[pn] = ok
    end
    -- issue #29: the p1 stub is shared by both gate variants (0x04 meaty / 0x05 true
    -- combo); detect either and record which, so 1b bundles (REF v.1) read as present
    if has.p1 then
      local g = rom(0x01BE23)
      has.p1 = (g == 0x04 or g == 0x05)
      has.p1gate = has.p1 and g or nil
    end
    local det = {}
    for _, e in ipairs(PATCH_IDS) do det[#det + 1] = e.id .. "=" .. (has[e.id] and "Y" or "-") end
    if has.p1gate then det[1] = det[1] .. string.format("(gate %02X)", has.p1gate) end
    log("detect: " .. table.concat(det, " "))
    -- pre-flight (#4): every savestate the selected tests reference must exist,
    -- reported all at once, before any test runs
    local missing, seen = {}, {}
    for _, tst in ipairs(T) do
      local wanted = (not tst.need or tst.need()) and (not ONLY or tst.name:find(ONLY, 1, true))
      if wanted and tst.state and not seen[tst.state] then
        seen[tst.state] = true
        local f = io.open(TRACE .. tst.state, "rb")
        if f then f:close() else missing[#missing + 1] = tst.state end
      end
    end
    if #missing > 0 then
      log("MISSING FIXTURES (" .. #missing .. "): " .. table.concat(missing, ", "))
      log("aborting — restore them from git (traces/*.mss are force-added) before running")
      emu.stop(1); return
    end
    local nfail = 0
    for r, exp in pairs(MATRIX_ROWS) do
      for c = 0, 15 do
        if rom(0xD081 + r * 16 + c) ~= exp[c + 1] then nfail = nfail + 1 end
      end
    end
    results[#results + 1] = { name = "static-matrix-integrity", ok = nfail == 0, msg = nfail .. " byte mismatches" }
    log(string.format("%s static-matrix-integrity", nfail == 0 and "PASS" or "FAIL"))
    local rfail = 0
    for _, rec in ipairs(DESP_RECORDS) do
      for i = 0, 6 do
        if rom(rec[1] + i) ~= tonumber(rec[2]:sub(i * 2 + 1, i * 2 + 2), 16) then rfail = rfail + 1 end
      end
    end
    results[#results + 1] = { name = "static-desperation-records", ok = rfail == 0, msg = rfail .. " byte mismatches" }
    log(string.format("%s static-desperation-records", rfail == 0 and "PASS" or "FAIL"))
    local hfail = 0
    for i = 0, #MOD_HANDLERS_HEX / 2 - 1 do
      if rom(MOD_HANDLERS_OFF + i) ~= tonumber(MOD_HANDLERS_HEX:sub(i * 2 + 1, i * 2 + 2), 16) then hfail = hfail + 1 end
    end
    results[#results + 1] = { name = "static-modifier-handlers", ok = hfail == 0, msg = hfail .. " byte mismatches" }
    log(string.format("%s static-modifier-handlers", hfail == 0 and "PASS" or "FAIL"))
    -- ⚠ The exp-tier anime line's double-health forces the ACS health stat at
    -- the copy, inside this very span: $C0:87DF `lda $1D0A` (ad 0a 1d) becomes
    -- `lda #imm / nop` (a9 xx ea). That is deliberate, so the check accepts
    -- EITHER form -- but it stays a byte-identity check in both, splicing the
    -- override into the expected image rather than masking the bytes out.
    local expect = CHARLOADER_HEX
    if rom(CHARLOADER_OFF + 15) == 0xA9 and rom(CHARLOADER_OFF + 17) == 0xEA then
      expect = expect:sub(1, 30)
            .. string.format("a9%02xea", rom(CHARLOADER_OFF + 16))
            .. expect:sub(37)
    end
    local cfail = 0
    for i = 0, #expect / 2 - 1 do
      if rom(CHARLOADER_OFF + i) ~= tonumber(expect:sub(i * 2 + 1, i * 2 + 2), 16) then cfail = cfail + 1 end
    end
    results[#results + 1] = { name = "static-charloader-acs", ok = cfail == 0, msg = cfail .. " byte mismatches" }
    log(string.format("%s static-charloader-acs", cfail == 0 and "PASS" or "FAIL"))
    if EXPECT == "clean" then
      local any = false
      for _, e in ipairs(PATCH_IDS) do if has[e.id] then any = true end end
      results[#results + 1] = { name = "static-expect-clean", ok = not any, msg = "patches detected on clean ROM" }
    elseif EXPECT == "all" then
      local all = true
      for _, e in ipairs(PATCH_IDS) do if not has[e.id] then all = false end end
      results[#results + 1] = { name = "static-expect-all", ok = all, msg = "missing patches on all-patches ROM" }
    end
    phase = "next"
  end
  if phase == "next" then
    idx = idx + 1
    while T[idx] and ((T[idx].need and not T[idx].need()) or (ONLY and not T[idx].name:find(ONLY, 1, true))) do
      if not (ONLY and not T[idx].name:find(ONLY, 1, true)) then
        log("SKIP " .. T[idx].name .. " (patch absent)")
      end
      idx = idx + 1
    end
    if not T[idx] then
      local np, nf = 0, 0
      for _, r in ipairs(results) do if r.ok then np = np + 1 else nf = nf + 1; log("  FAILED: " .. r.name .. " — " .. r.msg) end end
      log(nf == 0 and ("ALL PASS (" .. np .. ")") or ("FAILURES (" .. nf .. "/" .. (np + nf) .. ")"))
      emu.stop(nf == 0 and 0 or 1); return
    end
    stateFile = T[idx].state; needLoad = true
    phase = "settle"; settle = 0
    return
  end
  if phase == "settle" then
    settle = settle + 1
    if not needLoad and settle >= 3 then
      phase = "run"; testT0 = t; hits = {}; pulse = {}
      hpSeed = { [0x1049] = ram(0x1049), [0x10C9] = ram(0x10C9) }
      curTest = T[idx]; curTest.mem = {}
    end
    return
  end
  if phase == "run" then
    local api = { pt = t - testT0, mem = curTest.mem }
    curTest.frame(api)
    if api.pt >= curTest.dur then
      local ok, msg = curTest.verdict({ pt = api.pt, mem = curTest.mem })
      results[#results + 1] = { name = curTest.name, ok = ok, msg = msg or "" }
      log(string.format("%s %s%s", ok and "PASS" or "FAIL", curTest.name, ok and "" or (" — " .. (msg or ""))))
      curTest = nil; pulse = {}
      phase = "next"
    end
  end
